function sortCrimeList() {
    const crimeList = document.getElementById('crimeList');
    const items = crimeList.getElementsByClassName('list-group-item');

    // Converte os itens em uma matriz para poder usar o método sort
    const itemsArray = Array.from(items);

    // Ordena a matriz em ordem alfabética
    itemsArray.sort((a, b) => a.textContent.localeCompare(b.textContent));

    // Remove os itens existentes da lista
    itemsArray.forEach(item => crimeList.removeChild(item));

    // Adiciona os itens ordenados de volta à lista
    itemsArray.forEach(item => crimeList.appendChild(item));
}
